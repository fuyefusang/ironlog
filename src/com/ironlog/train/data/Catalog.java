    public static Map<String, List<Exercise>> byMuscle() {
        Map<String, List<Exercise>> map = new LinkedHashMap<>();
        for (String m : MUSCLES) {
            map.put(m, new ArrayList<Exercise>());
        }
        for (Exercise e : builtIn()) {
            List<Exercise> l = map.get(e.muscle);
            if (l != null) {
                l.add(e);
            }
        }
        return map;
    }

